"use client";
import React, { useState } from "react";
import {
  FileText,
  X,
  Download,
  Printer,
  CheckCircle2,
  Building2,
  Calendar,
  MapPin,
  Hash,
  Loader2,
} from "lucide-react";
import { SocialGrievance, mockPublicWorks } from "@/data/mockData";

interface CpgramsModalProps {
  grievance: SocialGrievance | null;
  onClose: () => void;
}

export default function CpgramsModal({ grievance, onClose }: CpgramsModalProps) {
  const [downloaded, setDownloaded] = useState(false);
  const [generating, setGenerating] = useState(false);

  if (!grievance) return null;

  const work = mockPublicWorks.find(
    (w) => w.id === grievance.related_project_id
  );

  const today = new Date().toLocaleDateString("en-IN", {
    day: "2-digit",
    month: "long",
    year: "numeric",
  });

  const generatedAt = new Date().toLocaleString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: true,
  });

  const refNo = `CPGRAMS/GCC/${grievance.id.toString().padStart(4, "0")}/2026`;
  const fileName = `Sanchal_Grievance_${grievance.related_project_id ?? grievance.id}.pdf`;

  // ─────────────────────────────────────────────────────────────────────────
  // jsPDF PDF generation — purely client-side, no backend required
  // ─────────────────────────────────────────────────────────────────────────
  const handleDownload = async () => {
    setGenerating(true);

    try {
      // Dynamic import keeps jspdf out of the initial bundle
      const jsPDFModule = await import("jspdf");
      const { default: jsPDF } = jsPDFModule;
      const autoTableModule = await import("jspdf-autotable");
      const autoTable = autoTableModule.default;

      const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
      const PAGE_W = 210;
      const MARGIN = 18;
      const CONTENT_W = PAGE_W - MARGIN * 2;

      // ── Design tokens ─────────────────────────────────────────────────────
      const BLUE_DARK: [number, number, number] = [15, 23, 42];
      const BLUE_MID: [number, number, number] = [30, 64, 175];
      const BLUE_ACCENT: [number, number, number] = [59, 130, 246];
      const RED: [number, number, number] = [239, 68, 68];
      const AMBER: [number, number, number] = [245, 158, 11];
      const GREEN: [number, number, number] = [16, 185, 129];
      const GRAY_DARK: [number, number, number] = [30, 41, 59];
      const GRAY_MID: [number, number, number] = [100, 116, 139];
      const GRAY_LIGHT: [number, number, number] = [241, 245, 249];
      const WHITE: [number, number, number] = [255, 255, 255];

      const riskColor = (): [number, number, number] => {
        if (!work) return GRAY_MID;
        if (work.delay_risk_score > 75) return RED;
        if (work.delay_risk_score >= 40) return AMBER;
        return GREEN;
      };

      const urgencyColor = (): [number, number, number] => {
        if (grievance.urgency_tier === "HIGH") return RED;
        if (grievance.urgency_tier === "MEDIUM") return AMBER;
        return GREEN;
      };

      let cursorY = 0;

      // ── HEADER BAND ───────────────────────────────────────────────────────
      doc.setFillColor(...BLUE_DARK);
      doc.rect(0, 0, PAGE_W, 28, "F");

      doc.setFillColor(...BLUE_ACCENT);
      doc.rect(0, 26, PAGE_W, 2, "F");

      doc.setFont("helvetica", "bold");
      doc.setFontSize(13);
      doc.setTextColor(...WHITE);
      doc.text("OFFICIAL CPGRAMS / RTI GRIEVANCE DRAFT", PAGE_W / 2, 11, { align: "center" });

      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(
        "Generated by Sanchal — AI Municipal Intelligence Platform · Greater Chennai Corporation",
        PAGE_W / 2,
        18,
        { align: "center" }
      );

      cursorY = 36;

      // ── GOVERNMENT OF INDIA SEAL LINE ─────────────────────────────────────
      doc.setFillColor(...GRAY_LIGHT);
      doc.roundedRect(MARGIN, cursorY, CONTENT_W, 14, 2, 2, "F");

      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(...BLUE_MID);
      doc.text("GOVERNMENT OF INDIA", MARGIN + 4, cursorY + 5.5);

      doc.setFont("helvetica", "normal");
      doc.setFontSize(7.5);
      doc.setTextColor(...GRAY_MID);
      doc.text(
        "Ministry of Personnel, Public Grievances and Pensions · Central Public Grievance Redress & Monitoring System",
        MARGIN + 4,
        cursorY + 10.5
      );

      doc.setFont("courier", "bold");
      doc.setFontSize(8);
      doc.setTextColor(...BLUE_MID);
      doc.text(refNo, MARGIN + CONTENT_W - 4, cursorY + 5.5, { align: "right" });

      cursorY += 20;

      // ── DOCUMENT TITLE ────────────────────────────────────────────────────
      doc.setFont("helvetica", "bold");
      doc.setFontSize(12);
      doc.setTextColor(...BLUE_DARK);
      doc.text("GRIEVANCE SUBMISSION FORM", PAGE_W / 2, cursorY, { align: "center" });
      cursorY += 4;
      doc.setDrawColor(...BLUE_ACCENT);
      doc.setLineWidth(0.5);
      doc.line(MARGIN + 30, cursorY, PAGE_W - MARGIN - 30, cursorY);
      cursorY += 7;

      // ── SUBJECT LINE ──────────────────────────────────────────────────────
      const roadLabel = work?.road_name ?? grievance.location_mention ?? "Chennai Road Network";
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8.5);
      doc.setTextColor(...GRAY_DARK);
      doc.text("Subject:", MARGIN, cursorY);
      doc.setFont("helvetica", "normal");
      const subjectText = `Complaint regarding uncoordinated excavation and delayed public works on ${roadLabel}`;
      const subjectLines = doc.splitTextToSize(subjectText, CONTENT_W - 22);
      doc.text(subjectLines, MARGIN + 20, cursorY);
      cursorY += subjectLines.length * 4.5 + 5;

      // ── FILING METADATA TABLE ─────────────────────────────────────────────
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(...BLUE_MID);
      doc.text("FILING DETAILS", MARGIN, cursorY);
      cursorY += 3;

      autoTable(doc, {
        startY: cursorY,
        margin: { left: MARGIN, right: MARGIN },
        tableWidth: CONTENT_W,
        styles: { fontSize: 8, cellPadding: 3, lineColor: [226, 232, 240], lineWidth: 0.3 },
        headStyles: { fillColor: BLUE_MID, textColor: WHITE, fontStyle: "bold", fontSize: 7.5 },
        alternateRowStyles: { fillColor: [248, 250, 252] },
        columnStyles: {
          0: { cellWidth: 50, fontStyle: "bold", textColor: GRAY_DARK },
          1: { cellWidth: CONTENT_W - 50 },
        },
        head: [["Field", "Value"]],
        body: [
          ["Reference No.", refNo],
          ["Date of Filing", today],
          ["Generated At", generatedAt],
          ["Source Platform", `${grievance.platform} · ${grievance.user_handle}`],
          ["Location of Concern", grievance.location_mention ?? "Greater Chennai"],
          ["Urgency Classification", grievance.urgency_tier],
          ["Public Engagement", `${grievance.likes} Likes · ${grievance.retweets} Retweets`],
        ],
        didParseCell: (data) => {
          if (data.cell.raw === grievance.urgency_tier && data.section === "body") {
            data.cell.styles.textColor = urgencyColor();
            data.cell.styles.fontStyle = "bold";
          }
        },
      });

      cursorY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 7;

      // ── GRIEVANCE DESCRIPTION ─────────────────────────────────────────────
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(...BLUE_MID);
      doc.text("GRIEVANCE DESCRIPTION", MARGIN, cursorY);
      cursorY += 4;

      doc.setFillColor(...GRAY_LIGHT);
      const descLines = doc.splitTextToSize(grievance.content, CONTENT_W - 6);
      const descBoxH = descLines.length * 4.8 + 6;
      doc.roundedRect(MARGIN, cursorY, CONTENT_W, descBoxH, 2, 2, "F");
      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(...GRAY_DARK);
      doc.text(descLines, MARGIN + 3, cursorY + 5);
      cursorY += descBoxH + 7;

      // ── LINKED PROJECT TABLE ──────────────────────────────────────────────
      if (work) {
        doc.setFont("helvetica", "bold");
        doc.setFontSize(9);
        doc.setTextColor(...BLUE_MID);
        doc.text("LINKED PUBLIC WORKS PROJECT (AUTO-DETECTED)", MARGIN, cursorY);
        cursorY += 3;

        autoTable(doc, {
          startY: cursorY,
          margin: { left: MARGIN, right: MARGIN },
          tableWidth: CONTENT_W,
          styles: { fontSize: 8, cellPadding: 3, lineColor: [226, 232, 240], lineWidth: 0.3 },
          headStyles: { fillColor: BLUE_MID, textColor: WHITE, fontStyle: "bold", fontSize: 7.5 },
          alternateRowStyles: { fillColor: [240, 249, 255] },
          columnStyles: {
            0: { cellWidth: 55, fontStyle: "bold", textColor: GRAY_DARK },
            1: { cellWidth: CONTENT_W - 55 },
          },
          head: [["Field", "Value"]],
          body: [
            ["Project ID", work.id],
            ["Road / Site", work.road_name],
            ["Department", work.department],
            ["Contractor", work.contractor],
            ["Start Date", work.start_date],
            ["Planned End Date", work.end_date],
            ["Delay Risk Score", `${work.delay_risk_score}%`],
            ["Current Status", work.status.replace(/_/g, " ")],
            [
              "Estimated Cost (Cr)",
              work.estimated_cost_cr ? `Rs. ${work.estimated_cost_cr} Cr` : "N/A",
            ],
          ],
          didParseCell: (data) => {
            if (data.cell.raw === `${work.delay_risk_score}%` && data.section === "body") {
              data.cell.styles.textColor = riskColor();
              data.cell.styles.fontStyle = "bold";
            }
          },
        });

        cursorY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 7;
      }

      // ── ACTION REQUIRED ───────────────────────────────────────────────────
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(...BLUE_MID);
      doc.text("ACTION REQUIRED", MARGIN, cursorY);
      cursorY += 5;

      const actions = [
        "Immediate site inspection within 48 hours by a competent authority.",
        "Contractor to submit a signed compliance and progress report forthwith.",
        "Safety barricading audit to be conducted by the Public Works Department.",
        "Status update to be filed on the CPGRAMS portal within 7 working days.",
        "Coordination meeting to be convened between overlapping departments.",
      ];

      actions.forEach((action, idx) => {
        doc.setFont("helvetica", "bold");
        doc.setFontSize(8);
        doc.setTextColor(...BLUE_ACCENT);
        doc.text(`${idx + 1}.`, MARGIN + 1, cursorY);
        doc.setFont("helvetica", "normal");
        doc.setTextColor(...GRAY_DARK);
        const wrapped = doc.splitTextToSize(action, CONTENT_W - 10);
        doc.text(wrapped, MARGIN + 7, cursorY);
        cursorY += wrapped.length * 4.5 + 2;
      });

      cursorY += 4;

      // ── LEGAL BOILERPLATE ─────────────────────────────────────────────────
      doc.setFillColor(...GRAY_LIGHT);
      doc.roundedRect(MARGIN, cursorY, CONTENT_W, 22, 2, 2, "F");
      doc.setFont("helvetica", "italic");
      doc.setFontSize(7);
      doc.setTextColor(...GRAY_MID);
      const legal = [
        "This grievance draft has been automatically generated by Sanchal, an AI-powered Municipal Intelligence Platform",
        "operated by the Greater Chennai Corporation under the Right to Information Act, 2005 and the Central Public",
        "Grievance Redress & Monitoring System (CPGRAMS) framework. The citizen is advised to submit this document",
        "through the official CPGRAMS portal at https://pgportal.gov.in or by registered post to the respective department.",
        "Failure to address this grievance within the stipulated time may constitute a violation of statutory obligations.",
      ];
      legal.forEach((line, i) => doc.text(line, MARGIN + 3, cursorY + 5 + i * 3.4));
      cursorY += 28;

      // ── SIGNATURE SECTION ─────────────────────────────────────────────────
      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(...GRAY_DARK);
      doc.text("Petitioner's Signature: _____________________________", MARGIN, cursorY);
      doc.text("Date: _______________", PAGE_W - MARGIN - 50, cursorY, { align: "left" });
      cursorY += 8;
      doc.text("Name: ___________________________________________", MARGIN, cursorY);
      cursorY += 8;
      doc.text("Contact No.: ________________________________", MARGIN, cursorY);

      // ── FOOTER BAND ───────────────────────────────────────────────────────
      const PAGE_H = 297;
      doc.setFillColor(...BLUE_DARK);
      doc.rect(0, PAGE_H - 14, PAGE_W, 14, "F");
      doc.setFillColor(...BLUE_ACCENT);
      doc.rect(0, PAGE_H - 14, PAGE_W, 1.5, "F");

      doc.setFont("helvetica", "normal");
      doc.setFontSize(7);
      doc.setTextColor(148, 163, 184);
      doc.text(
        `Sanchal v4.0 · Greater Chennai Corporation · Ref: ${refNo} · Generated: ${generatedAt}`,
        PAGE_W / 2,
        PAGE_H - 5,
        { align: "center" }
      );

      // ── SAVE ──────────────────────────────────────────────────────────────
      doc.save(fileName);
      setDownloaded(true);
    } catch (err) {
      console.error("PDF generation failed:", err);
      alert("PDF generation failed. Please try again.");
    } finally {
      setGenerating(false);
    }
  };

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm"
      onClick={onClose}
    >
      <div
        className="relative w-full max-w-2xl bg-[#0D0F14] border border-[#1E2330] rounded-2xl shadow-2xl overflow-hidden"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="flex items-center justify-between px-5 py-4 border-b border-[#1E2330] bg-[#090B0F]">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-[#3B82F6]/15 flex items-center justify-center">
              <FileText size={15} color="#60A5FA" />
            </div>
            <div>
              <h2 className="text-[13px] font-semibold text-white">
                CPGRAMS Auto-Draft
              </h2>
              <p className="text-[9.5px] text-[#4B5563]">
                Central Public Grievance Redress &amp; Monitoring System
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="w-7 h-7 rounded-md bg-[#13161D] flex items-center justify-center text-[#4B5563] hover:text-white transition-colors"
          >
            <X size={13} />
          </button>
        </div>

        {/* Document body */}
        <div className="p-5 max-h-[70vh] overflow-y-auto space-y-4">
          {/* Document header */}
          <div className="bg-[#13161D] border border-[#1E2330] rounded-xl p-4">
            <div className="flex items-center justify-between mb-3">
              <div className="flex items-center gap-2">
                <Building2 size={14} color="#60A5FA" />
                <span className="text-[11px] font-bold text-[#60A5FA] tracking-wide">
                  GOVERNMENT OF INDIA
                </span>
              </div>
              <span className="text-[10px] text-[#4B5563] font-mono">{refNo}</span>
            </div>
            <h3 className="text-[14px] font-bold text-white text-center mb-1">
              GRIEVANCE SUBMISSION FORM
            </h3>
            <p className="text-[10px] text-[#4B5563] text-center">
              Central Public Grievance Redress &amp; Monitoring System · Ministry of
              Personnel, Public Grievances and Pensions
            </p>
          </div>

          {/* Meta grid */}
          <div className="grid grid-cols-2 gap-3">
            <Field icon={<Hash size={11} />} label="Reference No." value={refNo} />
            <Field
              icon={<Calendar size={11} />}
              label="Date of Filing"
              value={today}
            />
            <Field
              icon={<MapPin size={11} />}
              label="Location"
              value={grievance.location_mention}
            />
            <Field
              icon={<FileText size={11} />}
              label="Urgency Tier"
              value={grievance.urgency_tier}
              valueColor={
                grievance.urgency_tier === "HIGH"
                  ? "#EF4444"
                  : grievance.urgency_tier === "MEDIUM"
                  ? "#F59E0B"
                  : "#10B981"
              }
            />
          </div>

          {/* Grievance text */}
          <div className="bg-[#13161D] border border-[#1E2330] rounded-xl p-4">
            <p className="text-[9.5px] text-[#4B5563] uppercase tracking-widest font-semibold mb-2">
              Grievance Description
            </p>
            <p className="text-[12px] text-[#D1D5DB] leading-relaxed">
              {grievance.content}
            </p>
            <div className="flex items-center gap-3 mt-3 pt-3 border-t border-[#1E2330]">
              <span className="text-[10px] text-[#4B5563]">
                Source: <span className="text-[#9CA3AF]">{grievance.platform}</span>{" "}
                · <span className="text-[#9CA3AF]">{grievance.user_handle}</span>
              </span>
            </div>
          </div>

          {/* Linked project */}
          {work && (
            <div className="bg-[#0A1B2E] border border-[#1E3A5F] rounded-xl p-4">
              <p className="text-[9.5px] text-[#60A5FA] uppercase tracking-widest font-semibold mb-3">
                Linked Public Works Project (Auto-Detected)
              </p>
              <div className="grid grid-cols-2 gap-2">
                <Field label="Project ID" value={work.id} mono />
                <Field label="Road" value={work.road_name} />
                <Field label="Department" value={work.department} />
                <Field label="Contractor" value={work.contractor} />
                <Field
                  label="Delay Risk"
                  value={`${work.delay_risk_score}%`}
                  valueColor={
                    work.delay_risk_score > 75
                      ? "#EF4444"
                      : work.delay_risk_score >= 40
                      ? "#F59E0B"
                      : "#10B981"
                  }
                />
                <Field
                  label="Status"
                  value={work.status.replace(/_/g, " ")}
                  valueColor={
                    work.status === "CRITICAL_OVERLAP"
                      ? "#EF4444"
                      : work.status === "MODERATE_RISK"
                      ? "#F59E0B"
                      : "#10B981"
                  }
                />
              </div>
            </div>
          )}

          {/* Action required */}
          <div className="bg-[#13161D] border border-[#1E2330] rounded-xl p-4">
            <p className="text-[9.5px] text-[#4B5563] uppercase tracking-widest font-semibold mb-2">
              Action Required
            </p>
            <ol className="space-y-1.5">
              {[
                "Immediate site inspection within 48 hours.",
                "Contractor to submit compliance & progress report.",
                "Safety barricading audit to be conducted by PWD.",
                "Status update to be filed within 7 working days.",
              ].map((action, i) => (
                <li key={i} className="flex items-start gap-2 text-[11px] text-[#9CA3AF]">
                  <span className="text-[#374151] font-mono">{i + 1}.</span>
                  {action}
                </li>
              ))}
            </ol>
          </div>
        </div>

        {/* Footer */}
        <div className="flex items-center justify-between px-5 py-4 border-t border-[#1E2330] bg-[#090B0F]">
          <div className="flex items-center gap-2">
            {downloaded && (
              <div className="flex items-center gap-1.5 text-[10px] text-[#10B981]">
                <CheckCircle2 size={12} />
                <span>PDF downloaded — {fileName}</span>
              </div>
            )}
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={onClose}
              className="text-[12px] text-[#4B5563] hover:text-[#9CA3AF] px-3 py-1.5 transition-colors"
            >
              Close
            </button>
            <button
              onClick={() => window.print()}
              className="flex items-center gap-1.5 bg-[#13161D] border border-[#1E2330] text-[#9CA3AF] text-[12px] font-medium px-3 py-2 rounded-lg hover:border-[#374151] transition-colors"
            >
              <Printer size={13} />
              Print
            </button>
            <button
              id="cpgrams-download-pdf"
              onClick={handleDownload}
              disabled={generating}
              className="flex items-center gap-2 bg-[#3B82F6] hover:bg-[#2563EB] disabled:opacity-60 disabled:cursor-wait text-white text-[12px] font-semibold px-4 py-2 rounded-lg transition-colors shadow-lg shadow-blue-900/30"
            >
              {generating ? (
                <>
                  <Loader2 size={13} className="animate-spin" />
                  Generating…
                </>
              ) : (
                <>
                  <Download size={13} />
                  Download Official Grievance PDF
                </>
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}

// ─────────────────────────────────────────────────────────────────────────────
// Field helper component (unchanged from Phase 3)
// ─────────────────────────────────────────────────────────────────────────────
function Field({
  icon,
  label,
  value,
  valueColor,
  mono,
}: {
  icon?: React.ReactNode;
  label: string;
  value: string;
  valueColor?: string;
  mono?: boolean;
}) {
  return (
    <div className="flex flex-col gap-0.5">
      <div className="flex items-center gap-1">
        {icon && <span className="text-[#4B5563]">{icon}</span>}
        <span className="text-[9.5px] text-[#4B5563] uppercase tracking-wider font-medium">
          {label}
        </span>
      </div>
      <span
        className={`text-[11px] font-semibold leading-tight ${mono ? "font-mono" : ""}`}
        style={{ color: valueColor ?? "#D1D5DB" }}
      >
        {value}
      </span>
    </div>
  );
}
